-- Serviços. O saldo não concluído permanece no mesmo serviço.
create table if not exists public.rework_services (
  id uuid primary key default gen_random_uuid(),
  service_code text not null unique,
  reference text not null,
  description text not null,
  planned_quantity integer not null check (planned_quantity > 0),
  withdrawn_quantity integer not null default 0 check (withdrawn_quantity >= 0),
  completed_quantity integer not null default 0 check (completed_quantity >= 0),
  returned_quantity integer not null default 0 check (returned_quantity >= 0),
  cause text,
  priority_score numeric(12,2) not null default 0,
  priority_override integer,
  status text not null default 'Pendente' check (status in ('Pendente','Aguardando retirada','Em execução','Parcial','Concluído','Impedimento','Cancelado')),
  assigned_to uuid references auth.users(id),
  created_by uuid not null references auth.users(id),
  started_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.rework_services enable row level security;
drop policy if exists "services read authenticated" on public.rework_services;
create policy "services read authenticated" on public.rework_services for select to authenticated using (true);
drop policy if exists "services insert authenticated" on public.rework_services;
create policy "services insert authenticated" on public.rework_services for insert to authenticated with check (created_by = auth.uid() or public.current_app_role()='admin');
drop policy if exists "services update authorized" on public.rework_services;
create policy "services update authorized" on public.rework_services for update to authenticated using (public.current_app_role() in ('admin','operacao')) with check (public.current_app_role() in ('admin','operacao'));
drop policy if exists "admin delete services" on public.rework_services;
create policy "admin delete services" on public.rework_services for delete to authenticated using (public.current_app_role()='admin');

