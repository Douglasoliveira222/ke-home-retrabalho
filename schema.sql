create extension if not exists pgcrypto;

-- Perfis e permissões
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (username = lower(username) and username ~ '^[a-z0-9._-]{3,40}$'),
  display_name text not null default '',
  role text not null default 'operacao' check (role in ('admin','gestao','operacao')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.profiles enable row level security;

create or replace function public.current_app_role()
returns text language sql stable security definer set search_path = ''
as $$ select p.role from public.profiles p where p.id = auth.uid() and p.active = true limit 1 $$;

create or replace function public.handle_new_rework_user()
returns trigger language plpgsql security definer set search_path = '' as $$
declare requested_username text;
begin
  requested_username := lower(coalesce(new.raw_user_meta_data ->> 'username', ''));
  if requested_username !~ '^[a-z0-9._-]{3,40}$' then
    raise exception 'Nome de usuário inválido. Use 3 a 40 letras, números, ponto, hífen ou sublinhado.';
  end if;
  insert into public.profiles (id, username, display_name, role)
  values (new.id, requested_username, coalesce(new.raw_user_meta_data ->> 'display_name',''), 'operacao');
  return new;
end; $$;
drop trigger if exists on_rework_auth_user_created on auth.users;
create trigger on_rework_auth_user_created after insert on auth.users for each row execute function public.handle_new_rework_user();

drop policy if exists "profile self read" on public.profiles;
create policy "profile self read" on public.profiles for select to authenticated using (id = auth.uid() or public.current_app_role() = 'admin');
drop policy if exists "admin manage profiles" on public.profiles;
create policy "admin manage profiles" on public.profiles for update to authenticated using (public.current_app_role() = 'admin') with check (public.current_app_role() = 'admin');

